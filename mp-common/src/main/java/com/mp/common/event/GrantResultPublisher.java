package com.mp.common.event;

/**
 * 发奖结果事件的发布口。V3 PR-9 引入。
 *
 * <p><b>发布侧只认这个接口，不认传输</b>。V3 是单进程（《分阶段方案》§6.1「V3 仍为单进程，V4 才拆」）， 实现是进程内事件总线；V4 拆分布式后换成 RocketMQ
 * 普通消息，{@code reward} 的发布代码一行不动。
 *
 * <p><b>为什么 V3 不直接接 RocketMQ</b>：这一层要验的是「事件加速、查单保证」这条分工是否成立 ——
 * 而它由<b>消费侧的幂等与查单任务并存</b>决定，与传输是进程内还是跨进程无关。V3 接真实 broker 只能 让每次 IT 多起一个容器，验不出额外的东西；「至少一次投递」「broker
 * 停机」这类真实 MQ 语义留给 V4 退出标准第 5 条。
 *
 * <p><b>接口存在本身是有代价的，此处的代价是值得的</b>：它把「换传输」这件事的影响面锁定在一个 实现类里。若 V3 直接调 Spring 的 {@code
 * ApplicationEventPublisher}，V4 时要在 {@code reward} 的业务 代码里找出每一处发布点 —— 而那时改的是已经被用例锁定的代码。
 */
public interface GrantResultPublisher {

    /**
     * 发布一条发奖结果事件。
     *
     * <p><b>发布失败不得让调用方失败</b>：事件是加速手段，它没送到只意味着收敛退回查单周期。实现类 负责吞掉异常并记日志 ——
     * 把发布异常抛给调用方会让一次已经成功的回调处理被判为失败，进而 触发重试，那是用「更强的一致性要求」去保护一条本就允许丢的通路。
     */
    void publish(RewardGrantResultEvent event);
}
